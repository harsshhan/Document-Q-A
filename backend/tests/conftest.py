class FakeS3Client:
    """In-memory stand-in for the boto3 S3 client.

    Only the calls the application makes are implemented, and stored objects are
    kept in a plain dict so tests can assert on keys and bodies without a
    network round trip.
    """

    def __init__(self) -> None:
        self.objects: dict[tuple[str, str], bytes] = {}
        # Recorded so tests can prove no ACL (i.e. no public-read) is ever sent.
        self.acl_arguments: list[dict] = []
        self.presigned_requests: list[dict] = []
        # Arguments boto3's Session was built with (credentials, region).
        self.session_kwargs: dict = {}

    def put_object(self, *, Bucket, Key, Body, ContentType=None, **kwargs):
        if "ACL" in kwargs:
            self.acl_arguments.append(kwargs)
        self.objects[(Bucket, Key)] = Body
        return {}

    def get_object(self, *, Bucket, Key):
        from botocore.exceptions import ClientError

        if (Bucket, Key) not in self.objects:
            raise ClientError(
                {"Error": {"Code": "NoSuchKey", "Message": "Not Found"}},
                "GetObject",
            )
        return {"Body": io.BytesIO(self.objects[(Bucket, Key)])}

    def delete_object(self, *, Bucket, Key, **kwargs):
        self.objects.pop((Bucket, Key), None)
        return {}

    def generate_presigned_url(
        self, ClientMethod, Params=None, ExpiresIn=None, **kwargs
    ):
        Params = Params or {}
        self.presigned_requests.append(
            {"method": ClientMethod, "params": Params, "expires_in": ExpiresIn}
        )
        return (
            f"https://{Params.get('Bucket')}.s3.amazonaws.com/{Params.get('Key')}"
            f"?X-Amz-Expires={ExpiresIn}&X-Amz-Signature=fake"
        )


@pytest.fixture(autouse=True)
def fake_s3(monkeypatch):
    """Replace boto3's session so every test runs without AWS.

    ``services.s3_storage._create_client`` still runs for real, so the way the
    region and credentials are passed is exercised; only the network client is
    swapped for the in-memory fake.
    """

    from services import s3_storage

    client = FakeS3Client()

    class _FakeSession:
        def __init__(self, **kwargs):
            client.session_kwargs = kwargs

        def client(self, service, **kwargs):
            return client

    monkeypatch.setattr(s3_storage.boto3.session, "Session", _FakeSession)
    return client


async def _purge_test_users() -> None:
    from sqlalchemy import delete
    from sqlalchemy.ext.asyncio import create_async_engine

    from db.models import User

    engine = create_async_engine(TEST_DATABASE_URL)
    async with engine.begin() as connection:
        await connection.execute(delete(User).where(User.username.like("user_%")))
    await engine.dispose()


